def ocean_openapi_schema():
    """
    Generate an OpenAPI schema and inject Ocean Professional branding via CSS in Swagger UI.
    We will override the default docs to apply custom CSS and a polished look.
    """
    if app.openapi_schema:
        return app.openapi_schema
    openapi_schema = get_openapi(
        title=app.title,
        version=app.version,
        description=app.description,
        routes=app.routes,
    )
    app.openapi_schema = openapi_schema
    return app.openapi_schema


