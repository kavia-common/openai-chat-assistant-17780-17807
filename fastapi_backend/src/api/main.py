def _convert_messages_for_openai(messages: List[ChatMessage]) -> List[dict]:
    """
    Convert Pydantic ChatMessage list to OpenAI-compatible message dicts.
    """
    converted = []
    for m in messages:
        role = m.role.lower().strip()
        if role not in {"system", "user", "assistant"}:
            raise HTTPException(status_code=422, detail=f"Invalid role '{m.role}'. Must be one of: system, user, assistant.")
        converted.append({"role": role, "content": m.content})
    return converted


# PUBLIC_INTERFACE
@app.post(
    "/chat",
    response_model=ChatResponse,
    summary="Send chat messages",
    description="Send conversation messages and receive an AI-generated assistant response using OpenAI.",
    tags=["Chat"],
    responses={
        200: {"description": "AI response generated successfully."},
        422: {"description": "Validation error for request payload or message roles."},
        500: {"description": "Server error (missing configuration or OpenAI SDK not available)."},
    },
)
def chat(request: ChatRequest) -> ChatResponse:
    """
    Generate an AI response to the provided conversation messages using OpenAI Chat Completions.

    Parameters:
        request (ChatRequest): Conversation history and optional generation parameters.

    Returns:
        ChatResponse: Assistant response message and optional usage metrics.
    """
    settings = get_settings()
    client = create_openai_client(settings)

    model = request.model or settings["model_fallback"] or "gpt-4o-mini"
    payload_messages = _convert_messages_for_openai(request.messages)

    try:
        # Using the new OpenAI Python SDK interface (>=1.0.0)
        completion = client.chat.completions.create(
            model=model,
            messages=payload_messages,
            temperature=request.temperature,
            top_p=request.top_p,
            max_tokens=request.max_tokens,
        )
    except Exception as e:
        raise HTTPException(status_code=HTTP_500_INTERNAL_SERVER_ERROR, detail=f"OpenAI chat completion failed: {str(e)}")

    # Extract the assistant message and usage (if present)
    try:
        choice = completion.choices[0]
        assistant_content = choice.message.content or ""
        usage = getattr(completion, "usage", None)
        prompt_tokens = getattr(usage, "prompt_tokens", None) if usage else None
        completion_tokens = getattr(usage, "completion_tokens", None) if usage else None
        total_tokens = getattr(usage, "total_tokens", None) if usage else None
    except Exception:
        assistant_content = ""
        prompt_tokens = completion_tokens = total_tokens = None

    return ChatResponse(
        message=ChatMessage(role="assistant", content=assistant_content),
        model=model,
        usage_prompt_tokens=prompt_tokens,
        usage_completion_tokens=completion_tokens,
        usage_total_tokens=total_tokens,
    )
