# PUBLIC_INTERFACE
class ChatMessage(BaseModel):
    """Represents a single chat message with role and content."""
    role: str = Field(..., description="Role of the message sender. One of: 'user', 'assistant', or 'system'.", examples=["user"])
    content: str = Field(..., description="The textual content of the message.", examples=["Hello!"])

# PUBLIC_INTERFACE
class ChatRequest(BaseModel):
    """Request body for sending chat messages to the assistant."""
    messages: List[ChatMessage] = Field(..., description="Ordered list of chat messages forming the conversation history.")
    model: Optional[str] = Field(default=None, description="Optional OpenAI chat model to use. Defaults via env MODEL_FALLBACK.")
    temperature: Optional[float] = Field(default=0.7, ge=0.0, le=2.0, description="Sampling temperature for response.")
    top_p: Optional[float] = Field(default=1.0, ge=0.0, le=1.0, description="Nucleus sampling parameter.")
    max_tokens: Optional[int] = Field(default=512, ge=1, description="Maximum tokens for the assistant response.")

# PUBLIC_INTERFACE
class ChatResponse(BaseModel):
    """Response body containing the assistant message."""
    message: ChatMessage = Field(..., description="The assistant's message as generated by the model.")
    model: str = Field(..., description="The model used to generate the response.")
    usage_prompt_tokens: Optional[int] = Field(None, description="Prompt tokens used (if available).")
    usage_completion_tokens: Optional[int] = Field(None, description="Completion tokens used (if available).")
    usage_total_tokens: Optional[int] = Field(None, description="Total tokens used (if available).")

# PUBLIC_INTERFACE
class HealthResponse(BaseModel):
    """Health check response."""
    status: str = Field(..., description="Service status string.")
    openai_ready: bool = Field(..., description="Whether OpenAI client can be initialized (API key present and SDK import OK).")

# PUBLIC_INTERFACE
class DocsTheme(BaseModel):
    """Theme configuration exposed via docs-theme endpoint."""
    name: str = Field(..., description="Theme name")
